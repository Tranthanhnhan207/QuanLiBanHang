     private void hienThiSanPham() {
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblSanPham.getModel();

    model.setRowCount(0);

    try {
        try (java.sql.Connection conn = KetNoi.layKetNoi()) {
            String sql = "SELECT MaSP, TenSP, MaLoai, DonGia, SoLuong FROM SANPHAM";
            
            try (java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {
                java.sql.ResultSet rs = ps.executeQuery();
                
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getString("MaSP"),
                        rs.getString("TenSP"),
                        rs.getString("MaLoai"),
                        rs.getDouble("DonGia"),
                        rs.getInt("SoLuong")
                    });
                }
                
                rs.close();
            }
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Lỗi hiển thị sản phẩm: " + e.getMessage());
    }
}
